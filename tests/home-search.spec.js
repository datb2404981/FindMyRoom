test('no matches and invalid searches have separate recoverable states on home', async ({ page }) => {
  await page.goto('/#/')
  await submit(page, 'Lam Thư')
  await expect(page.getByRole('heading', { name: 'Không tìm thấy kết quả phù hợp!', exact: true })).toBeVisible()
  await submit(page, 'khongcophongnay')
  await expect(page.getByRole('heading', { name: 'Không tìm thấy kết quả phù hợp!', exact: true })).toBeVisible()
  await expect(page.locator('.home-listing-group')).toHaveCount(0)
  expect(page.url()).not.toContain('/tim-tro')
  await submit(page, '!!!')
  await expect(page.getByRole('alert')).toContainText('Dữ liệu không hợp lệ!')
  await expect(page.getByRole('textbox', { name: 'Từ khóa tìm kiếm', exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: 'Nhập lại tìm kiếm', exact: true }).click()
  await expect(page.locator('.group-rentals .room-card')).toHaveCount(4)
  await page.goto('/#/?search=1&school=invalid-school')
  await expect(page.getByRole('alert')).toContainText('Dữ liệu không hợp lệ!')
  await expect(page.locator('.home-listing-group')).toHaveCount(0)
})

test('pagination preserves the search and shows only published listings', async ({ page }) => {
  await page.goto('/#/')
  await page.evaluate(() => {
    const key = 'findmyroom-demo-v1'
    const data = JSON.parse(localStorage.getItem(key))
    const template = data.posts[0]
    for (let index = 0; index < 5; index++) data.posts.push({ ...template, id: 'pagination-' + index, title: 'Phòng thử phân trang ' + index, house: 'Nhà trọ kiểm thử ' + index, kind: 'rental', status: 'Đang hiển thị' })
    data.posts.push({ ...template, id: 'pending-post', title: 'Phòng thử phân trang chưa duyệt', kind: 'rental', status: 'Chờ duyệt' })
    localStorage.setItem(key, JSON.stringify(data))
  })
  await page.reload()
  await submit(page, 'Phòng thử phân trang')
  await expect(page.locator('.group-rentals .room-card')).toHaveCount(4)
  await page.getByRole('navigation', { name: 'Phân trang kết quả', exact: true }).getByRole('button', { name: 'Trang 2', exact: true }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.locator('.group-rentals .room-card')).toHaveCount(1)
  await expect(page.locator('.group-roommates')).toHaveCount(0)
  await expect(page.locator('.group-houses')).toHaveCount(0)
  await expect(page.locator('.group-rentals')).toContainText('Phòng thử phân trang 4')
  await expect(page.locator('.group-rentals')).not.toContainText('chưa duyệt')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Từ khóa tìm kiếm', exact: true })).toHaveValue('Phòng thử phân trang')
  await expect(page.getByRole('button', { name: 'Trang 2', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('button', { name: 'Trang trước', exact: true }).click()
  await expect(page.locator('.group-rentals .room-card')).toHaveCount(4)
})

test('old search links resolve to home and grouped results fit mobile and desktop', async ({ page }) => {
  await page.goto('/#/tim-tro?district=Ninh%20Ki%E1%BB%81u')
  await expect(page).toHaveURL(/#\/\?.*search=1/)
  expect(page.url()).not.toContain('/tim-tro')
  await expect(page.locator('.group-rentals .room-card')).toHaveCount(2)
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}: horizontal overflow`).toBeTruthy()
    await expect(page.locator('.group-rentals .room-card').first()).toBeVisible()
  }
  await page.setViewportSize({ width: 375, height: 900 })
  const navigation = page.getByRole('navigation', { name: 'Điều hướng điện thoại', exact: true })
  await expect(navigation.getByRole('link')).toHaveCount(3)
  await expect(navigation.getByRole('link', { name: 'Tìm trọ', exact: true })).toHaveCount(0)
})

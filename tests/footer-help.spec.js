import { test, expect } from '@playwright/test'

test('footer help opens the matching popup without navigating and restores keyboard focus', async ({ page }) => {
  await page.goto('/#/ghep-tro')
  const originalUrl = page.url()
  const footer = page.locator('.site-footer')
  for (const [title, content] of [['Quy tắc ghép trọ', 'Chia sẻ việc nhà'], ['Cảnh báo lừa đảo', 'Bảo vệ thông tin cá nhân']]) {
    const trigger = footer.getByRole('button', { name: title, exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: title, exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog).toContainText(content)
    await expect(page).toHaveURL(originalUrl)
    const close = dialog.getByRole('button', { name: 'Đóng thông tin', exact: true })
    await expect(close).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('button', { name: 'Đã hiểu', exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(close).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  }
})

test('footer help fits a phone and can close by confirmation or outside click', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 844 })
  await page.goto('/#/')
  const footer = page.locator('.site-footer')
  await footer.getByRole('button', { name: 'Cảnh báo lừa đảo', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  const box = await dialog.boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(375)
  expect(box.y + box.height).toBeLessThanOrEqual(844)
  await dialog.getByRole('button', { name: 'Đã hiểu', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await footer.getByRole('button', { name: 'Quy tắc ghép trọ', exact: true }).click()
  await expect(dialog).toBeVisible()
  await page.mouse.click(4, 4)
  await expect(dialog).toHaveCount(0)
  await expect(page).toHaveURL(/#\/$/)
})

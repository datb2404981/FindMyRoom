import { test, expect } from '@playwright/test'

for (const width of [1366, 390]) {
  test(`house edit popup preserves data, cancels and saves across tabs at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/#/dang-nhap?redirect=/quan-ly/nha-tro')
    await page.getByLabel('Email *', { exact: true }).fill('chutro@example.com')
    await page.getByLabel('Mật khẩu *', { exact: true }).fill('demopass123')
    await page.locator('form').getByRole('button', { name: 'Đăng nhập', exact: true }).click()
    const edit = page.getByRole('button', { name: 'Chỉnh sửa Nhà trọ Minh An', exact: true })
    await edit.click()
    const dialog = page.getByRole('dialog', { name: 'Chỉnh sửa nhà trọ', exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByLabel('Tên nhà trọ *', { exact: true })).toHaveValue('Nhà trọ Minh An')
    await dialog.getByLabel('Tên nhà trọ *', { exact: true }).fill('Thay đổi chưa lưu')
    await dialog.getByRole('button', { name: 'Hủy', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await edit.click()
    await expect(dialog.getByLabel('Tên nhà trọ *', { exact: true })).toHaveValue('Nhà trọ Minh An')
    await dialog.getByLabel('Tên nhà trọ *', { exact: true }).fill('Nhà trọ đã cập nhật')
    await dialog.getByRole('button', { name: 'Vị trí & Địa lý', exact: true }).click()
    await expect(dialog.getByLabel('Địa chỉ *', { exact: true })).not.toHaveValue('')
    await dialog.getByRole('button', { name: 'Hình ảnh', exact: true }).click()
    const photoCount = await dialog.locator('.thumbnail-card').count()
    const transfer = await page.evaluateHandle(() => {
      const data = new DataTransfer()
      const bytes = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+kvKkAAAAASUVORK5CYII='), c => c.charCodeAt(0))
      data.items.add(new File([bytes], 'room.png', { type: 'image/png' }))
      return data
    })
    await dialog.locator('.upload-dropzone').dispatchEvent('drop', { dataTransfer: transfer })
    await expect(dialog.locator('.thumbnail-card')).toHaveCount(photoCount + 1)
    const cover = await dialog.locator('.thumbnail-card img').last().getAttribute('src')
    await dialog.getByRole('button', { name: 'Đặt làm ảnh bìa', exact: true }).last().click()
    await expect(dialog.locator('.thumbnail-card img').first()).toHaveAttribute('src', cover)
    await expect(dialog.locator('.thumbnail-card').first().getByText('Ảnh bìa', { exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Thông tin chung', exact: true }).click()
    await expect(dialog.getByLabel('Tên nhà trọ *', { exact: true })).toHaveValue('Nhà trọ đã cập nhật')
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    const footer = await dialog.locator('.house-editor-footer').boundingBox()
    expect(footer.y + footer.height).toBeLessThanOrEqual(900)
    await page.screenshot({ path: test.info().outputPath(`house-editor-${width}.png`), fullPage: true })
    await dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await page.reload()
    await expect(page.locator('.house-row').filter({ hasText: 'Nhà trọ đã cập nhật' }).locator('img')).toHaveAttribute('src', cover)
    await page.getByRole('button', { name: 'Chỉnh sửa Nhà trọ đã cập nhật', exact: true }).click()
    await expect(dialog.getByLabel('Tên nhà trọ *', { exact: true })).toHaveValue('Nhà trọ đã cập nhật')
    await dialog.getByRole('button', { name: 'Hình ảnh', exact: true }).click()
    await expect(dialog.locator('.thumbnail-card')).toHaveCount(photoCount + 1)
    await expect(dialog.locator('.thumbnail-card img').first()).toHaveAttribute('src', cover)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
  })
}
